// Generates every wire artifact from the contracts in docs/08-rewrite/contracts/.
//   node tools/wire/gen-wire.mjs           write the outputs
//   node tools/wire/gen-wire.mjs --check   fail when an output differs from its source
// Outputs are deterministic (LF, no timestamps).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as yaml from "js-yaml";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const contracts = path.join(root, "docs", "08-rewrite", "contracts");
const check = process.argv.includes("--check");

const read = (name) => fs.readFileSync(path.join(contracts, name), "utf8");
const api = yaml.load(read("api.openapi.yaml"));
const live = JSON.parse(read("live-channels.json"));
const setupKeys = JSON.parse(read("setup-keys.json"));

const header = (src, comment) =>
  `${comment} Generated by tools/wire/gen-wire.mjs from docs/08-rewrite/contracts/${src}. Do not edit.`;

// ---- naming and literals -------------------------------------------------

const pascal = (s) =>
  s
    .split("_")
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("");

const rsStr = (s) =>
  `"${[...s]
    .map((c) => {
      if (c === "\\") return "\\\\";
      if (c === '"') return '\\"';
      if (c === "\n") return "\\n";
      const cp = c.codePointAt(0);
      return cp < 0x20 || cp > 0x7e ? `\\u{${cp.toString(16)}}` : c;
    })
    .join("")}"`;

const rsF64 = (n) => {
  const s = String(n);
  return /^-?\d+$/.test(s) ? `${s}.0` : s;
};
const rsOpt = (v, f) => (v === undefined || v === null ? "None" : `Some(${f(v)})`);
const tsStr = (s) => JSON.stringify(s);

// ---- wire.schema.json ----------------------------------------------------

function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node && typeof node === "object") {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      out[k] = k === "$ref" && typeof v === "string" ? v.replace("#/components/schemas/", "#/$defs/") : rewriteRefs(v);
    }
    return out;
  }
  return node;
}

function wireSchema() {
  const schemas = api.components.schemas;
  const wire = {
    $schema: "https://json-schema.org/draft/2020-12/schema",
    $id: "https://iracing-coach.local/wire.schema.json",
    $comment: "Generated by tools/wire/gen-wire.mjs from docs/08-rewrite/contracts/api.openapi.yaml components.schemas. Do not edit.",
    $defs: rewriteRefs(schemas),
  };
  return JSON.stringify(wire, null, 2) + "\n";
}

// ---- live channels -------------------------------------------------------

const CHANNEL_TYPES = ["f32", "f64", "u8", "i8", "u16", "u32", "bool8", "enum8"];

function enumTables() {
  // name -> [{ name, value }]
  const out = {};
  for (const [name, def] of Object.entries(live.enums)) {
    out[name] = Array.isArray(def)
      ? def.map((v, i) => ({ name: pascal(v), value: i }))
      : Object.entries(def).map(([v, value]) => ({ name: pascal(v), value }));
  }
  return out;
}
const ENUM_RUST = { flag_state: "FlagState", gap_trend: "GapTrend", run_phase: "RunPhase", evidence: "Evidence", priority: "Priority" };

function validateLive() {
  live.channels.forEach((c, i) => {
    if (c.index !== i) throw new Error(`live-channels: channel ${c.id} has index ${c.index}, expected ${i}`);
    if (!CHANNEL_TYPES.includes(c.type)) throw new Error(`live-channels: channel ${c.id} has unknown type ${c.type}`);
    if (c.type === "enum8" && !live.enums[c.enum]) throw new Error(`live-channels: channel ${c.id} names unknown enum ${c.enum}`);
  });
  live.cues.forEach((c, i) => {
    if (c.id !== i + 1) throw new Error(`live-channels: cue ${c.key} has id ${c.id}, expected ${i + 1}`);
    if (!(c.priority in live.enums.priority)) throw new Error(`live-channels: cue ${c.key} has unknown priority ${c.priority}`);
    if (!live.enums.evidence.includes(c.evidence)) throw new Error(`live-channels: cue ${c.key} has unknown evidence ${c.evidence}`);
  });
  const ids = new Set(live.channels.map((c) => c.id));
  ids.add("cue");
  for (const t of live.tiles) {
    for (const ch of t.channel.split(",")) if (!ids.has(ch)) throw new Error(`live-channels: tile ${t.id} names unknown channel ${ch}`);
  }
  const tileUnits = new Set(live.tiles.flatMap((t) => t.units ?? []));
  for (const unit of Object.keys(live.unit_labels)) {
    if (!tileUnits.has(unit)) throw new Error(`live-channels: unit_labels names unit ${unit}, which no tile lists`);
  }
}

function liveRust() {
  validateLive();
  const enums = enumTables();
  const o = [];
  o.push(header("live-channels.json", "//"));
  o.push("");
  o.push(`pub const TABLE_VERSION: u16 = ${live.table_version};`);
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
  o.push(`pub enum ChannelType { ${CHANNEL_TYPES.map(pascal).join(", ")} }`);
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
  o.push("pub struct ChannelSpec {");
  o.push("    pub index: u16,");
  o.push("    pub id: &'static str,");
  o.push("    pub ty: ChannelType,");
  o.push("    pub unit: Option<&'static str>,");
  o.push("    pub enum_name: Option<&'static str>,");
  o.push("}");
  o.push("");
  o.push("pub static CHANNELS: &[ChannelSpec] = &[");
  for (const c of live.channels) {
    o.push(
      `    ChannelSpec { index: ${c.index}, id: ${rsStr(c.id)}, ty: ChannelType::${pascal(c.type)}, unit: ${rsOpt(c.unit, rsStr)}, enum_name: ${rsOpt(c.enum, rsStr)} },`,
    );
  }
  o.push("];");
  for (const [key, rustName] of Object.entries(ENUM_RUST)) {
    const members = enums[key];
    o.push("");
    o.push("#[repr(u8)]");
    o.push("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]");
    o.push(`pub enum ${rustName} {`);
    for (const m of members) o.push(`    ${m.name} = ${m.value},`);
    o.push("}");
    o.push("");
    o.push(`impl ${rustName} {`);
    o.push("    pub const fn from_u8(value: u8) -> Option<Self> {");
    o.push("        match value {");
    for (const m of members) o.push(`            ${m.value} => Some(Self::${m.name}),`);
    o.push("            _ => None,");
    o.push("        }");
    o.push("    }");
    o.push("}");
  }
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq, Eq)]");
  o.push("pub enum ArgFormat { Ceil, Int, Fixed2, Percent0 }");
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq)]");
  o.push("pub struct CueSpec {");
  o.push("    pub id: u8,");
  o.push("    pub key: &'static str,");
  o.push("    pub priority: Priority,");
  o.push("    pub evidence: Evidence,");
  o.push("    pub template: &'static str,");
  o.push("    pub basis: Option<&'static str>,");
  o.push("    pub args: &'static [ArgFormat],");
  o.push("}");
  o.push("");
  o.push("pub static CUES: &[CueSpec] = &[");
  for (const c of live.cues) {
    const args = c.args.map((a) => `ArgFormat::${pascal(a.format)}`).join(", ");
    o.push(
      `    CueSpec { id: ${c.id}, key: ${rsStr(c.key)}, priority: Priority::${pascal(c.priority)}, evidence: Evidence::${pascal(c.evidence)}, template: ${rsStr(c.template)}, basis: ${rsOpt(c.basis, rsStr)}, args: &[${args}] },`,
    );
  }
  o.push("];");
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq)]");
  o.push("pub enum Conversion { Scale(f64), ScaleOffset { scale: f64, offset: f64 } }");
  o.push("");
  o.push("/// Display-unit conversion from a channel unit; identity when `from == to`.");
  o.push("pub fn conversion(from: &str, to: &str) -> Option<Conversion> {");
  o.push("    if from == to {");
  o.push("        return Some(Conversion::Scale(1.0));");
  o.push("    }");
  o.push("    match (from, to) {");
  for (const [from, targets] of Object.entries(live.unit_conversions)) {
    for (const [to, v] of Object.entries(targets)) {
      const body = typeof v === "number" ? `Conversion::Scale(${rsF64(v)})` : `Conversion::ScaleOffset { scale: ${rsF64(v.scale)}, offset: ${rsF64(v.offset)} }`;
      o.push(`        (${rsStr(from)}, ${rsStr(to)}) => Some(${body}),`);
    }
  }
  o.push("        _ => None,");
  o.push("    }");
  o.push("}");
  o.push("");
  o.push("/// Display label of a unit id (`unit_labels`); a unit without an entry displays as written.");
  o.push("pub fn unit_label(unit: &str) -> &str {");
  o.push("    match unit {");
  for (const [unit, label] of Object.entries(live.unit_labels)) o.push(`        ${rsStr(unit)} => ${rsStr(label)},`);
  o.push("        other => other,");
  o.push("    }");
  o.push("}");
  o.push("");
  o.push("#[derive(Debug, Clone, Copy, PartialEq)]");
  o.push("pub struct TileSpec {");
  o.push("    pub id: &'static str,");
  o.push("    pub label: &'static str,");
  o.push("    pub channels: &'static [&'static str],");
  o.push("    pub units: &'static [&'static str],");
  o.push("    pub format: Option<&'static str>,");
  o.push("    pub style: &'static str,");
  o.push("    pub precision: u8,");
  o.push("    pub min: Option<f64>,");
  o.push("    pub max: Option<f64>,");
  o.push("    pub step: bool,");
  o.push("}");
  o.push("");
  o.push("pub static TILES: &[TileSpec] = &[");
  for (const t of live.tiles) {
    const channels = t.channel.split(",").map(rsStr).join(", ");
    const units = (t.units ?? []).map(rsStr).join(", ");
    o.push(
      `    TileSpec { id: ${rsStr(t.id)}, label: ${rsStr(t.label)}, channels: &[${channels}], units: &[${units}], format: ${rsOpt(t.format, rsStr)}, style: ${rsStr(t.style)}, precision: ${t.precision}, min: ${rsOpt(t.min, rsF64)}, max: ${rsOpt(t.max, rsF64)}, step: ${t.step === true} },`,
    );
  }
  o.push("];");
  return o.join("\n") + "\n";
}

function liveTs() {
  validateLive();
  const enums = enumTables();
  const o = [];
  o.push(header("live-channels.json", "//"));
  o.push("");
  o.push(`export const TABLE_VERSION = ${live.table_version};`);
  o.push("");
  o.push(`export type ChannelType = ${CHANNEL_TYPES.map(tsStr).join(" | ")};`);
  o.push("");
  o.push("export interface ChannelSpec {");
  o.push("  readonly index: number;");
  o.push("  readonly id: string;");
  o.push("  readonly type: ChannelType;");
  o.push("  readonly unit: string | null;");
  o.push("  readonly enum: string | null;");
  o.push("}");
  o.push("");
  o.push("export const CHANNEL_BYTES: Readonly<Record<ChannelType, number>> = {");
  for (const [t, n] of Object.entries(live.types)) o.push(`  ${t}: ${n},`);
  o.push("};");
  o.push("");
  o.push("export const CHANNELS: readonly ChannelSpec[] = [");
  for (const c of live.channels) {
    o.push(`  { index: ${c.index}, id: ${tsStr(c.id)}, type: ${tsStr(c.type)}, unit: ${c.unit === undefined ? "null" : tsStr(c.unit)}, enum: ${c.enum === undefined ? "null" : tsStr(c.enum)} },`);
  }
  o.push("];");
  o.push("");
  o.push("export const CHANNEL_INDEX: Readonly<Record<string, number>> = {");
  for (const c of live.channels) o.push(`  ${c.id}: ${c.index},`);
  o.push("};");
  for (const [key, name] of Object.entries(ENUM_RUST)) {
    o.push("");
    o.push(`export const ${name} = {`);
    for (const m of enums[key]) o.push(`  ${m.name}: ${m.value},`);
    o.push("} as const;");
    o.push(`export type ${name} = (typeof ${name})[keyof typeof ${name}];`);
  }
  o.push("");
  o.push(`export type ArgFormat = ${["ceil", "int", "fixed2", "percent0"].map(tsStr).join(" | ")};`);
  o.push("");
  o.push("export interface CueSpec {");
  o.push("  readonly id: number;");
  o.push("  readonly key: string;");
  o.push("  readonly priority: Priority;");
  o.push("  readonly evidence: Evidence;");
  o.push("  readonly template: string;");
  o.push("  readonly basis: string | null;");
  o.push("  readonly args: readonly ArgFormat[];");
  o.push("}");
  o.push("");
  o.push("export const CUES: readonly CueSpec[] = [");
  for (const c of live.cues) {
    o.push(
      `  { id: ${c.id}, key: ${tsStr(c.key)}, priority: Priority.${pascal(c.priority)}, evidence: Evidence.${pascal(c.evidence)}, template: ${tsStr(c.template)}, basis: ${c.basis === undefined ? "null" : tsStr(c.basis)}, args: [${c.args.map((a) => tsStr(a.format)).join(", ")}] },`,
    );
  }
  o.push("];");
  o.push("");
  o.push("export type Conversion = { readonly scale: number; readonly offset: number };");
  o.push("");
  o.push("const CONVERSIONS: Readonly<Record<string, Readonly<Record<string, Conversion>>>> = {");
  for (const [from, targets] of Object.entries(live.unit_conversions)) {
    o.push(`  ${tsStr(from)}: {`);
    for (const [to, v] of Object.entries(targets)) {
      const scale = typeof v === "number" ? v : v.scale;
      const offset = typeof v === "number" ? 0 : v.offset;
      o.push(`    ${tsStr(to)}: { scale: ${scale}, offset: ${offset} },`);
    }
    o.push("  },");
  }
  o.push("};");
  o.push("");
  o.push("/** Display-unit conversion from a channel unit; identity when `from === to`. */");
  o.push("export function conversion(from: string, to: string): Conversion | null {");
  o.push("  if (from === to) return { scale: 1, offset: 0 };");
  o.push("  return CONVERSIONS[from]?.[to] ?? null;");
  o.push("}");
  o.push("");
  o.push("const UNIT_LABELS: ReadonlyMap<string, string> = new Map([");
  for (const [unit, label] of Object.entries(live.unit_labels)) o.push(`  [${tsStr(unit)}, ${tsStr(label)}],`);
  o.push("]);");
  o.push("");
  o.push("/** Display label of a unit id (`unit_labels`); a unit without an entry displays as written. */");
  o.push("export function unitLabel(unit: string): string {");
  o.push("  return UNIT_LABELS.get(unit) ?? unit;");
  o.push("}");
  o.push("");
  o.push("export interface TileSpec {");
  o.push("  readonly id: string;");
  o.push("  readonly label: string;");
  o.push("  readonly channels: readonly string[];");
  o.push("  readonly units: readonly string[];");
  o.push("  readonly format: string | null;");
  o.push("  readonly style: string;");
  o.push("  readonly precision: number;");
  o.push("  readonly min: number | null;");
  o.push("  readonly max: number | null;");
  o.push("  readonly step: boolean;");
  o.push("}");
  o.push("");
  o.push("export const TILES: readonly TileSpec[] = [");
  for (const t of live.tiles) {
    o.push(
      `  { id: ${tsStr(t.id)}, label: ${tsStr(t.label)}, channels: [${t.channel.split(",").map(tsStr).join(", ")}], units: [${(t.units ?? []).map(tsStr).join(", ")}], format: ${t.format === undefined ? "null" : tsStr(t.format)}, style: ${tsStr(t.style)}, precision: ${t.precision}, min: ${t.min ?? "null"}, max: ${t.max ?? "null"}, step: ${t.step === true} },`,
    );
  }
  o.push("];");
  return o.join("\n") + "\n";
}

// ---- setup keys ----------------------------------------------------------

function setupRust() {
  const o = [];
  o.push(header("setup-keys.json", "//"));
  o.push("");
  o.push(`pub const VERSION: u32 = ${setupKeys.version};`);
  o.push("");
  o.push("/// Regex (case-insensitive) over the last path segment of a `CarSetup` key, and the reason.");
  o.push("pub static EXCLUDED_LEAF_PATTERNS: &[(&str, &str)] = &[");
  for (const p of setupKeys.excluded_leaf_patterns) o.push(`    (${rsStr(p.pattern)}, ${rsStr(p.reason)}),`);
  o.push("];");
  return o.join("\n") + "\n";
}

function setupTs() {
  const o = [];
  o.push(header("setup-keys.json", "//"));
  o.push("");
  o.push(`export const VERSION = ${setupKeys.version};`);
  o.push("");
  o.push("/** Regex source (case-insensitive) over the last path segment of a CarSetup key, and the reason. */");
  o.push("export const EXCLUDED_LEAF_PATTERNS: readonly (readonly [pattern: string, reason: string])[] = [");
  for (const p of setupKeys.excluded_leaf_patterns) o.push(`  [${tsStr(p.pattern)}, ${tsStr(p.reason)}],`);
  o.push("];");
  return o.join("\n") + "\n";
}

// ---- api.d.ts ------------------------------------------------------------

async function apiTypes() {
  const ast = await openapiTS(structuredClone(api));
  return (
    "/** Generated by tools/wire/gen-wire.mjs from docs/08-rewrite/contracts/api.openapi.yaml. Do not edit. */\n\n" +
    astToString(ast).replace(/\r\n/g, "\n")
  );
}

// ---- run -----------------------------------------------------------------

const outputs = [
  ["web/src/gen/api.d.ts", await apiTypes()],
  ["crates/coach-wire/schema/wire.schema.json", wireSchema()],
  ["crates/coach-wire/src/gen/live_channels.rs", liveRust()],
  ["web/src/gen/live-channels.ts", liveTs()],
  ["crates/coach-wire/src/gen/setup_keys.rs", setupRust()],
  ["web/src/gen/setup-keys.ts", setupTs()],
];

let drift = 0;
for (const [rel, text] of outputs) {
  const file = path.join(root, rel);
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (current !== text) {
      console.error(`wire drift: ${rel}`);
      drift++;
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${rel}`);
  }
}
if (drift) {
  console.error("Run `pnpm gen:wire` and commit the result.");
  process.exit(1);
}
