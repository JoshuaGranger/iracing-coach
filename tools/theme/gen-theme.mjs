// config/theme.dark.json (canonical token source) -> web/src/gen/theme.css and theme.ts.
//   node tools/theme/gen-theme.mjs           write the outputs
//   node tools/theme/gen-theme.mjs --check   fail when an output differs from its source
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const check = process.argv.includes("--check");
const sourceRel = "config/theme.dark.json";
const theme = JSON.parse(fs.readFileSync(path.join(root, sourceRel), "utf8"));

const kebab = (s) => s.replace(/([a-z])([A-Z])/g, "$1-$2").toLowerCase();
const vars = [];
const add = (name, value) => vars.push([name, String(value)]);

for (const [k, v] of Object.entries(theme.colors)) add(`--color-${kebab(k)}`, v);
for (const [k, v] of Object.entries(theme.evidence)) add(`--evidence-${kebab(k)}`, v);
for (const [k, v] of Object.entries(theme.telemetry)) add(`--telemetry-${kebab(k)}`, v);

const t = theme.typography;
const family = (names) => names.map((n) => (/[\s]/.test(n) ? `"${n}"` : n)).join(", ");
add("--font-ui", family(t.uiFamilies));
add("--font-metric", family(t.metricFamilies));
// Sizes are authored in px against rootPx (the browser default, 16) and emitted in rem, so the root font size (the
// browser or OS default, then the driver's text-size step below) scales every type size, control height and space.
// Control heights keep a pixel floor so a small browser default cannot shrink a target under 36 px (desktop) or 44 px (touch).
const rem = (px) => `${Number((px / t.rootPx).toFixed(4))}rem`;
add("--text-body", rem(t.bodyPx));
add("--leading-body", rem(t.bodyLinePx));
add("--text-compact", rem(t.compactPx));
add("--text-control", rem(t.controlPx));
add("--text-data", rem(t.dataPx));
add("--text-section-title", rem(t.sectionTitlePx));
add("--text-page-title", rem(t.pageTitlePx));
add("--text-metric", rem(t.metricPx));
add("--control-height", `max(${t.controlHeightPx}px, ${rem(t.controlHeightPx)})`);
add("--touch-target", `max(${t.touchTargetPx}px, ${rem(t.touchTargetPx)})`);
t.weights.forEach((w, i) => add(`--weight-${["regular", "medium", "semibold"][i] ?? w}`, w));
theme.spacingPx.forEach((s, i) => add(`--space-${i + 1}`, rem(s)));
for (const [k, v] of Object.entries(theme.radiiPx)) add(`--radius-${kebab(k)}`, `${v}px`);

const m = theme.motionMs;
add("--motion-hover", `${m.hover}ms`);
add("--motion-structure", `${m.structure}ms`);
add("--motion-max-translate", `${m.maximumTranslationPx}px`);
add("--motion-easing", m.easing);
add("--nav-expanded", `${theme.window.expandedNavigationPx}px`);
add("--nav-collapsed", `${theme.window.collapsedNavigationPx}px`);

const css = [
  `/* Generated by tools/theme/gen-theme.mjs from ${sourceRel}. Do not edit. */`,
  ":root {",
  `  color-scheme: ${theme.mode};`,
  ...vars.map(([n, v]) => `  ${n}: ${v};`),
  "}",
  "",
  "/* Text size: the root font size of the driver's step (data-text-size on <html>; Default when absent). */",
  ...t.textSizes.flatMap((step) => [
    `${step.id === "default" ? ":root, " : ""}:root[data-text-size="${step.id}"] {`,
    `  font-size: ${step.percent}%;`,
    "}",
  ]),
  "",
  ...(m.honorReducedMotion
    ? [
        "@media (prefers-reduced-motion: reduce) {",
        "  :root {",
        "    --motion-hover: 0ms;",
        "    --motion-structure: 0ms;",
        "    --motion-max-translate: 0px;",
        "  }",
        "}",
        "",
      ]
    : []),
].join("\n");

const ts = [
  `// Generated by tools/theme/gen-theme.mjs from ${sourceRel}. Do not edit.`,
  "",
  `export const theme = ${JSON.stringify(theme, null, 2)} as const;`,
  "",
  "export type Theme = typeof theme;",
  "",
  "/** CSS custom properties emitted in theme.css, name -> value. */",
  "export const cssVariables: Readonly<Record<string, string>> = {",
  ...vars.map(([n, v]) => `  ${JSON.stringify(n)}: ${JSON.stringify(v)},`),
  "};",
  "",
].join("\n");

const outputs = [
  ["web/src/gen/theme.css", css],
  ["web/src/gen/theme.ts", ts],
];

let drift = 0;
for (const [rel, text] of outputs) {
  const file = path.join(root, rel);
  if (check) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
    if (current !== text) {
      console.error(`theme drift: ${rel}`);
      drift++;
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${rel}`);
  }
}
if (drift) {
  console.error("Run `pnpm gen:theme` and commit the result.");
  process.exit(1);
}
