"""Emit coach-numerics' Unicode tables from the running CPython 3.12.

Usage (from the repository root):

    python crates/coach-numerics/tools/gen_unicode.py            # write src/unicode_tables.rs
    python crates/coach-numerics/tools/gen_unicode.py --check    # compare, write nothing

Three properties of every code point, exactly as the interpreter answers them:

* the decimal digit value ``_PyUnicode_TransformDecimalAndSpaceToASCII`` uses
  (``Py_UNICODE_TODECIMAL``, the Unicode decimal value of category Nd), which
  ``float(str)`` and ``int(str)`` apply to a non-ASCII string;
* ``str.isspace()`` (``Py_UNICODE_ISSPACE``: bidirectional WS, B or S, or category Zs);
* ``str.isprintable()`` (``repr(str)`` escapes every character it rejects).

The tables depend only on the interpreter's Unicode database (3.12: Unicode
15.0.0), so Windows and Linux CPython 3.12 write the same file; ``--check``
under both proves it.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

CRATE = Path(__file__).resolve().parent.parent
OUT = CRATE / "src" / "unicode_tables.rs"

if sys.version_info[:2] != (3, 12):
    sys.exit(f"coach-numerics tables need CPython 3.12, not {sys.version.split()[0]}")


def ranges(predicate) -> list[tuple[int, int]]:
    """Inclusive ranges of the code points (surrogates included) where ``predicate`` holds."""

    out: list[tuple[int, int]] = []
    start = None
    for code in range(0x110000):
        if predicate(chr(code)):
            if start is None:
                start = code
        elif start is not None:
            out.append((start, code - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def decimal_runs() -> list[tuple[int, int, int]]:
    """``(first, last, value of first)``: consecutive code points whose decimal values count up."""

    runs: list[list[int]] = []
    for code in range(0x110000):
        value = unicodedata.decimal(chr(code), -1)
        if value < 0:
            continue
        if runs and runs[-1][1] == code - 1 and runs[-1][2] + (code - runs[-1][0]) == value:
            runs[-1][1] = code
        else:
            runs.append([code, code, value])
    return [tuple(run) for run in runs]  # type: ignore[misc]


def render() -> str:
    lines = [
        "// Generated by crates/coach-numerics/tools/gen_unicode.py from CPython "
        f"{sys.version_info[0]}.{sys.version_info[1]} (Unicode {unicodedata.unidata_version}).",
        "// Do not edit; regenerate and check with the tool.",
        "",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// `(first, last, decimal value of first)`: runs of code points with a decimal digit value.",
        "pub const DECIMAL: &[(u32, u32, u8)] = &[",
    ]
    lines += [f"    (0x{a:04X}, 0x{b:04X}, {v})," for a, b, v in decimal_runs()]
    lines += ["];", "", "/// Inclusive ranges where `str.isspace()` is true.", "pub const SPACE: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in ranges(str.isspace)]
    lines += ["];", "", "/// Inclusive ranges where `str.isprintable()` is false.", "pub const NOT_PRINTABLE: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:04X}, 0x{b:04X})," for a, b in ranges(lambda c: not c.isprintable())]
    lines += ["];", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="compare with the file on disk")
    args = parser.parse_args()
    text = render()
    if args.check:
        same = OUT.exists() and OUT.read_bytes() == text.encode("ascii")
        print(f"{OUT.name}: {'identical' if same else 'differs'} (Python {sys.version.split()[0]}, {sys.platform})")
        return 0 if same else 1
    OUT.write_bytes(text.encode("ascii"))
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
